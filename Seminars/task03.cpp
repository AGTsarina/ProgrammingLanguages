#include <iostream>

using namespace std;

// Объявление глобальной константы N = 10 – максимальный размер массива в стеке
const int N = 10;

// Базовый абстрактный класс "геометрическая фигура"
class fig {
protected: // Доступно только внутри класса и в классах-наследниках
    // Координаты центра фигуры (x0, y0)
    float x0, y0;
    // Два параметра фигуры: например, стороны, радиусы и т.п.
    float a, b;

public:
    // Конструктор с параметрами по умолчанию (значения 0 для всех аргументов)
    fig(float x1 = 0, float y1 = 0, float a1 = 0, float b1 = 0) :
        x0(x1), y0(y1), a(a1), b(b1) // Список инициализации членов класса
    {}

    // Конструктор копирования, принимает ссылку на другую фигуру
    fig(fig& f) : x0(f.x0), y0(f.y0), a(f.a), b(f.b) {}

    // Чисто виртуальный метод копирования (возвращает указатель на копию)
    // Обязан быть реализован в производных классах
    virtual fig* copyf() const = 0;

    // Чисто виртуальный метод вычисления площади (должен быть переопределён)
    virtual float plosh() const = 0;

    // Виртуальный метод печати параметров фигуры в поток
    virtual ostream& prfig(ostream& os) {
        // Выводим координаты x0 и y0
        return os << "x0 = " << x0 << ", y0 = " << y0;
    }

    // Дружественная функция (не член класса) перегрузки оператора <<
    // Позволяет выводить любую фигуру через cout << фигура
    friend ostream& operator<<(ostream& os, fig& f) {
        // Вызываем виртуальный метод prfig для полиморфного вывода
        return f.prfig(os);
    }

    // Виртуальный деструктор (обеспечивает правильное удаление объектов наследников)
    virtual ~fig() {}
};

// Класс "прямоугольный треугольник", наследник fig
class tre : public fig {
public:
    // Конструктор треугольника (принимает координаты и длины катетов)
    tre(float x1, float y1, float a1, float b1) :
        fig(x1, y1, a1, b1) // Вызов конструктора базового класса
    {}

    // Конструктор копирования треугольника
    tre(tre& f) : fig(f) // Копируем через конструктор копирования fig
    {}

    // Реализация чисто виртуального метода copyf – возвращает копию треугольника
    fig* copyf() const {
        // Создаём новый объект tre с теми же координатами и катетами
        return new tre(x0, y0, a, b);
    }

    // Реализация вычисления площади: (a * b) / 2 (половина произведения катетов)
    float plosh() const {
        return a * b / 2;
    }

    // Переопределение метода prfig для треугольника
    ostream& prfig(ostream& os) {
        // Сначала вызываем базовую версию (вывод x0, y0)
        fig::prfig(os);
        // Затем добавляем вывод катетов и переходим на новую строку
        return os << ", kat1 = " << a << ", kat2 = " << b << endl;
    }
};

// Класс "прямоугольник", наследник fig
class pr : public fig {
public:
    // Конструктор прямоугольника (координаты и стороны)
    pr(float x1, float y1, float a1, float b1) :
        fig(x1, y1, a1, b1) // Вызов конструктора базового класса
    {}

    // Конструктор копирования прямоугольника
    pr(pr& f) : fig(f) // Копируем через конструктор копирования fig
    {}

    // Реализация copyf – возвращает копию прямоугольника
    fig* copyf() const {
        return new pr(x0, y0, a, b);
    }

    // Площадь прямоугольника: произведение сторон
    float plosh() const {
        return a * b;
    }

    // Переопределение prfig для прямоугольника
    ostream& prfig(ostream& os) {
        // Сначала вывод координат от базового класса
        fig::prfig(os);
        // Затем вывод сторон и перевод строки
        return os << ", side1 = " << a << ", side2 = " << b << endl;
    }
};

// Класс "стек", хранящий указатели на фигуры (максимум N элементов)
class stk {
    int len;        // Текущее количество элементов в стеке
    int mlen;       // Максимальная ёмкость стека (не более N)
    fig* v[N];      // Массив указателей на фигуры (размер N – константа)

public:
    // Конструктор стека: задаётся максимальный размер n
    stk(int n) : len(0), mlen((n > N) ? N : n) // Если n больше N, то усекаем до N
    {}

    // Конструктор копирования стека (глубокое копирование)
    stk(const stk& fm) : len(fm.len), mlen(fm.mlen) {
        // Копируем каждый элемент, вызывая copyf() для полиморфного клонирования
        for (int i = 0; i < len; ++i)
            v[i] = fm.v[i]->copyf();
    }

    // Деструктор стека: удаляет все хранящиеся объекты
    ~stk() {
        for (int i = 0; i < len;)
            delete v[i++]; // удаляем указатель и переходим к следующему
    }

    // Дружественная функция вывода стека (перегрузка оператора <<)
    friend ostream& operator<<(ostream& os, stk& fs);

    // Возвращает текущий размер стека
    int get_size() { return len; }

    // Возвращает максимально возможный размер
    int get_msize() { return mlen; }

    // Извлечение элемента из стека (с вершины – с индексом 0, так реализовано)
    fig* pop() {
        if (!len) return 0;          // Если стек пуст, возвращаем nullptr
        fig* f = v[0];               // Запоминаем указатель на верхний элемент
        // Сдвигаем все оставшиеся элементы на одну позицию влево
        for (int i = 1; i < len; ++i)
            v[i - 1] = v[i];
        len--;                       // Уменьшаем счётчик
        return f;                    // Возвращаем извлечённый указатель
    }

    // Добавление элемента в стек (копирование объекта)
    int push(const fig& f) {
        if (len == mlen) {           // Проверка на переполнение
            cerr << "Error! Stack is full" << endl;
            return 0;                // Неудача
        }
        // Сдвигаем все существующие элементы вправо, освобождая позицию 0
        for (int i = len; i > 0; --i)
            v[i] = v[i - 1];
        len++;
        // Создаём копию переданной фигуры (вызов copyf) и помещаем в вершину
        v[0] = f.copyf();
        return 1;                    // Успех
    }
};

// Реализация оператора вывода для стека (дружественная функция)
ostream& operator<<(ostream& os, stk& f) {
    os << endl << "***** Stack of geometric objects: *****" << endl;
    // Проходим по всем элементам стека и выводим каждый, используя << фигуры
    for (int i = 0; i < f.len;)
        os << "i = " << i << ", figure=" << *f.v[i++] << endl;
    return os;
}

// Главная функция – точка входа в программу
int main() {
    // Вывод заголовка демонстрации
    cout << "=== Demonstration of stack ===\n\n";

    // Создаём стек с максимальным размером 5
    stk stack(5);

    // Создаём несколько объектов-фигур:
    tre triangle1(0, 0, 4, 3);    // треугольник с катетами 4 и 3
    tre triangle2(1, 1, 5, 2);    // треугольник с катетами 5 и 2
    pr rectangle1(2, 2, 6, 4);    // прямоугольник 6x4
    pr rectangle2(3, 3, 2, 2);    // прямоугольник 2x2

    // Сообщаем о начале помещения фигур в стек
    cout << "1. Pushing figures to stack:\n";
    // Вывод площади треугольника1 и добавление его в стек
    cout << "   - Triangle 1: area = " << triangle1.plosh() << endl;
    stack.push(triangle1);

    // Аналогично для треугольника2
    cout << "   - Triangle 2: area = " << triangle2.plosh() << endl;
    stack.push(triangle2);

    // Прямоугольник1
    cout << "   - Rectangle 1: area = " << rectangle1.plosh() << endl;
    stack.push(rectangle1);

    // Прямоугольник2
    cout << "   - Rectangle 2: area = " << rectangle2.plosh() << endl;
    stack.push(rectangle2);

    // Вывод содержимого стека (оператор <<)
    cout << "\n2. Stack contents:";
    cout << stack << endl;

    // Информация о текущем и максимальном размере стека
    cout << "3. Stack info:\n";
    cout << "   Current size: " << stack.get_size() << endl;
    cout << "   Maximum size: " << stack.get_msize() << endl;

    // Извлечение двух элементов из стека
    cout << "\n4. Popping elements from stack:\n";
    int numberToRemove = 2;           // сколько извлечь
    for (int i = 0; i < numberToRemove; i++) {
        fig* f = stack.pop();         // получаем указатель на извлечённую фигуру
        if (f) {                      // если не nullptr
            cout << "Popped: " << *f; // выводим её
            delete f;                 // удаляем объект, чтобы избежать утечки
        }
    }

    // Вывод стека после извлечения
    cout << "\n5. After popping elements:\n";
    cout << stack << endl;

    // Тест переполнения стека (создаём стек размером 2)
    cout << "\n6. Stack overflow test:\n";
    stk smallStack(2);
    smallStack.push(pr(0, 0, 1, 1));   // добавляем 1-й элемент – ок
    smallStack.push(pr(0, 0, 2, 2));   // добавляем 2-й элемент – ок
    smallStack.push(pr(0, 0, 3, 3));   // третий вызовет сообщение об ошибке

    // Демонстрация копирования стека (конструктор копирования)
    cout << "\n7. Stack copy demonstration:\n";
    stk originalStack(2);              // создаём оригинальный стек
    originalStack.push(tre(0, 0, 3, 4)); // добавляем треугольник
    originalStack.push(pr(0, 0, 5, 6));  // добавляем прямоугольник

    stk copiedStack = originalStack;   // вызов конструктора копирования

    // Вывод оригинального и скопированного стеков (они должны быть независимы)
    cout << "Original stack:" << originalStack;
    cout << "Copied stack:" << copiedStack;

    // Завершение программы (стек originalStack и copiedStack уничтожатся автоматически)
    return 0;
}
